class TestPricePredictionResponse:
    def test_create_response(self):
        response = PricePredictionResponse(id=1, predicted_price=250000.0)
        assert response.id == 1
        assert response.predicted_price == 250000.0

    def test_rejects_negative_price(self):
        import pytest
        from pydantic import ValidationError

        with pytest.raises(ValidationError):
            PricePredictionResponse(id=1, predicted_price=-100)


class TestPricePredictionBatchResponse:
    def test_create_batch_response(self):
        responses = [
            PricePredictionResponse(id=1, predicted_price=250000.0),
            PricePredictionResponse(id=2, predicted_price=300000.0),
        ]
        batch = PricePredictionBatchResponse(predictions=responses)
        assert len(batch.predictions) == 2
